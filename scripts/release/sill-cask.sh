#!/bin/sh
# Usage: sill-cask.sh <version> <sha256>
# Prints the Homebrew cask for a release, in the shape of AeroSpace's (nikitabobko/tap). Sill is signed with a
# self-signed certificate and not notarized, so the cask removes the quarantine attribute that Gatekeeper would
# otherwise refuse the app for.
set -eu

if [ "$#" -ne 2 ]; then
  echo "usage: $0 <version> <sha256>" >&2
  exit 1
fi
version=$1
sha256=$2

cat <<EOF
cask "sill" do # THE FILE IS GENERATED BY scripts/release/sill-cask.sh IN eai04191/sill
  version "$version"
  sha256 "$sha256"

  url "https://github.com/eai04191/sill/releases/download/#{version}/Sill-#{version}.zip"
  name "Sill"
  desc "Menu bar replacement with Liquid Glass"
  homepage "https://github.com/eai04191/sill"

  depends_on arch: :arm64
  depends_on macos: :tahoe

  app "Sill.app"

  postflight_steps do
    run "/usr/bin/xattr", args: ["-d", "com.apple.quarantine", "{{appdir}}/Sill.app"], must_succeed: false
  end
end
EOF
